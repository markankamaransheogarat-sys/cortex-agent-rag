import re
from typing import Dict, List


class HallucinationCriticAgent:
    """
    Critic Agent for Factuality & Faithfulness Verification.
    Validates that claims generated by the LLM are grounded in retrieved source context.
    Detects hallucinations and extracts unsupported assertions.
    """

    @staticmethod
    def _extract_sentences(text: str) -> List[str]:
        # Split by periods, exclamation, or question marks
        raw = re.split(r"(?<=[.!?])\s+", text.strip())
        return [s.strip() for s in raw if len(s.strip()) > 8]

    def verify_faithfulness(
        self,
        generated_answer: str,
        retrieved_contexts: List[Dict],
    ) -> Dict:
        """
        Evaluate if each sentence in the answer is grounded in the retrieved documents.
        """
        sentences = self._extract_sentences(generated_answer)
        if not sentences:
            return {
                "faithfulness_score": 1.0,
                "is_hallucination": False,
                "supported_claims": [],
                "unsupported_claims": [],
            }

        # Combine all source context text
        full_context = " ".join([c["content"].lower() for c in retrieved_contexts])
        context_words = set(re.findall(r"\b\w+\b", full_context))

        supported = []
        unsupported = []

        for sentence in sentences:
            s_words = set(re.findall(r"\b\w+\b", sentence.lower()))
            # Filter common stop words for fair lexical overlap test
            content_words = {w for w in s_words if len(w) > 3}

            if not content_words:
                supported.append(sentence)
                continue

            overlap = content_words.intersection(context_words)
            grounding_ratio = len(overlap) / len(content_words)

            # A claim is supported if >= 65% of its keywords exist in evidence
            if grounding_ratio >= 0.65:
                supported.append(sentence)
            else:
                unsupported.append(sentence)

        total_claims = len(sentences)
        faithfulness = round(len(supported) / total_claims, 2)
        is_hallucination = faithfulness < 0.80

        return {
            "faithfulness_score": faithfulness,
            "is_hallucination": is_hallucination,
            "supported_claims": supported,
            "unsupported_claims": unsupported,
        }
